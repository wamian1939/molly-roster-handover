"""Generate a reviewable SQLite/D1 schema from the current Roster Prisma model.

IDs and column names are unchanged. Dates stay ISO dates; instants are UTC ISO
strings. Arrays and JSON are JSON text. Decimals stay exact decimal strings.
Never runs a migration against a remote database.
"""
import json
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parents[3]
HERE = pathlib.Path(__file__).resolve().parents[1]


def models():
    source = (ROOT / "backend/prisma/schema.prisma").read_text(encoding="utf-8")
    enums = {name: body.split() for name, body in re.findall(r"enum (\w+)\s*\{([^}]+)\}", source)}
    names = re.findall(r"model (\w+)\s*\{", source)
    result = []
    for name, body in re.findall(r"model (\w+)\s*\{([^}]+)\}", source):
        table = re.search(r'@@map\("([^"]+)"\)', body).group(1)
        fields = []
        for line in body.splitlines():
            match = re.match(r"\s*(\w+)\s+(\w+)(\[\]|\?)?\s*(.*)", line)
            if not match or match[2] in names:
                continue
            column, kind, modifier, attrs = match.groups()
            fields.append({"name": column, "kind": kind, "array": modifier == "[]", "nullable": modifier == "?", "attrs": attrs})
        result.append({"name": name, "table": table, "fields": fields, "body": body})
    return result, enums


def generate():
    all_models, enums = models()
    sql = ["-- Generated from backend/prisma/schema.prisma; inspect before deployment.", "-- No seed records or employee data in this migration."]
    for model in all_models:
        columns = []
        for field in model["fields"]:
            name, kind, attrs = field["name"], field["kind"], field["attrs"]
            quoted = '"' + name + '"'
            storage = "INTEGER" if kind in ("Int", "Boolean") and not field["array"] else "TEXT"
            column = f"{quoted} {storage}" + ("" if field["nullable"] else " NOT NULL")
            if "@id" in attrs:
                column += " PRIMARY KEY"
            if "@unique" in attrs:
                column += " UNIQUE"
            default = re.search(r"@default\(([^\n]+)\)", attrs)
            if default:
                value = default[1]
                if value == "now()": column += " DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ','now'))"
                elif value == "[]": column += " DEFAULT '[]'"
                elif value in ("true", "false"): column += " DEFAULT " + str(int(value == "true"))
                elif value in enums.get(kind, []): column += " DEFAULT '" + value + "'"
                elif re.fullmatch(r"\d+", value): column += " DEFAULT " + value
                elif value.startswith('"'): column += " DEFAULT '" + json.loads(value).replace("'", "''") + "'"
                # cuid()/uuid() must be generated by the application, as Prisma does locally.
            if kind in enums: column += f" CHECK ({quoted} IN ({','.join(repr(x) for x in enums[kind])}))"
            if kind == "Boolean": column += f" CHECK ({quoted} IN (0,1))"
            if field["array"] or kind == "Json": column += f" CHECK (json_valid({quoted}))"
            if name == "version": column += f" CHECK ({quoted} >= 1)"
            columns.append(column)
        for column_list in re.findall(r"@@unique\(\[([^]]+)\]\)", model["body"]):
            columns.append("UNIQUE (" + ",".join('"' + c.strip() + '"' for c in column_list.split(",")) + ")")
        for relation in re.finditer(r"(\w+)\??\s+@relation\(fields: \[([^]]+)\], references: \[([^]]+)\], onDelete: (\w+)\)", model["body"]):
            target, local, remote, action = relation.groups()
            table = next(m["table"] for m in all_models if m["name"] == target)
            quote = lambda value: ",".join('"' + c.strip() + '"' for c in value.split(","))
            columns.append(f'FOREIGN KEY ({quote(local)}) REFERENCES "{table}" ({quote(remote)}) ON DELETE ' + {"Cascade": "CASCADE", "Restrict": "RESTRICT", "SetNull": "SET NULL"}[action] + " ON UPDATE CASCADE")
        checks = {
            "roster_periods": ['"startDate" <= "endDate"'],
            "shifts": ['"startAt" < "endAt"', '"breakMinutes" >= 0 AND "breakMinutes" < (julianday("endAt")-julianday("startAt"))*1440'],
            "shift_assignments": ['"officialScoreSnapshot" IS NULL OR CAST("officialScoreSnapshot" AS REAL) BETWEEN 0 AND 100', '"tierSnapshot" IS NULL OR "tierSnapshot" IN (\'T1\',\'T2\',\'T3\',\'T4\',\'T5\')'],
            "employee_availability": ['("status"=\'UNKNOWN\' AND "startAt" IS NULL AND "endAt" IS NULL) OR ("status" IN (\'AVAILABLE\',\'UNAVAILABLE\') AND "startAt" IS NOT NULL AND "endAt" IS NOT NULL AND "startAt" < "endAt")'],
            "shift_templates": ['"breakMinutes" >= 0'],
            "shift_roles": ['length("colorToken")=7 AND substr("colorToken",1,1)=\'#\' AND substr("colorToken",2) NOT GLOB \'*[^0-9A-Fa-f]*\''],
            "roster_store_settings": ['"slotIntervalMinutes" IN (15,30,60)', '"minimumShiftMinutes" >= "slotIntervalMinutes"', '"defaultBreakMinutes" >= 0', '"weekStartsOn" BETWEEN 0 AND 6', '"weeklyHourWarning" > 0 AND "dailyHourWarning" > 0'],
        }
        columns.extend("CHECK (" + c + ")" for c in checks.get(model["table"], []))
        sql.append(f'CREATE TABLE "{model["table"]}" (\n  ' + ",\n  ".join(columns) + "\n);")
        for index, columns_text in enumerate(re.findall(r"@@index\(\[([^]]+)\]\)", model["body"])):
            columns_text = ",".join('"' + c.strip() + '"' for c in columns_text.split(","))
            sql.append(f'CREATE INDEX "{model["table"]}_idx_{index}" ON "{model["table"]}" ({columns_text});')
    # PostgreSQL's GiST exclusion has no SQLite equivalent. Serialize overlap
    # enforcement inside the database statement instead of relying on a pre-read.
    for operation in ("INSERT", "UPDATE"):
        sql.append(f'''CREATE TRIGGER "period_no_overlap_{operation.lower()}" BEFORE {operation} ON roster_periods
WHEN EXISTS(SELECT 1 FROM roster_periods p WHERE p.storeId=NEW.storeId AND p.id<>NEW.id AND p.startDate<=NEW.endDate AND p.endDate>=NEW.startDate)
BEGIN SELECT RAISE(ABORT,'ROSTER_PERIOD_OVERLAP'); END;''')
    return "\n--> statement-breakpoint\n".join(sql) + "\n"


if __name__ == "__main__":
    target = HERE / "drizzle/0000_roster.sql"
    target.write_text(generate(), encoding="utf-8")
    print(json.dumps({"schema": str(target), "tables": len(models()[0])}))
